//! Wii disc layout reader (D116): parse the disc header, the partition
//! table and every partition's header into an EXACT coverage map of
//! the image, verify each partition body's hash tree against its own
//! plaintext, and walk the plaintext with the GameCube volume walker —
//! so the `wii-split/1` analyzer can decompose the image into
//! `assemble@1` pieces, one zero-input junk recipe, and per-partition
//! `xf-wii-crypt` routes.
//!
//! # The disc
//!
//! A Wii disc is a 0x400-byte header (game ID, disc number, the Wii
//! magic at 0x18, and at 0x60/0x61 the "no hashes" / "no encryption"
//! flags a retail master never sets), a partition table at 0x40000
//! (four groups of `(count, entries offset >> 2)`, each entry
//! `(partition offset >> 2, kind)`), region.bin at 0x4E000, and the
//! partitions themselves — each a 0x2C0-byte header (the ticket, then
//! the TMD / certificate chain / H3 table / data offsets and sizes,
//! all `>> 2`), the structures it points at, and the encrypted BODY:
//! `data_size` bytes of 32 KiB sectors (docs in `datboi-xf-wii-crypt`).
//! Every byte the tables do not name is mastering junk (the GameCube
//! generator seeded from the disc's ID and disc number, over the DISC's
//! address space), a zero pad, or residue.
//!
//! # A partition
//!
//! The body decrypts to a plaintext of `sectors × 0x7C00` bytes that
//! is a GameCube-shaped volume: boot block (Wii magic, offsets `>> 2`),
//! bi2, apploader, DOL, FST, files — and junk in every unused byte,
//! generated by the generator seeded from the PARTITION's own boot
//! block ID and disc number over the PLAINTEXT's address space (measured
//! on a real disc: the update and channel partitions, whose IDs differ
//! from the disc's, match their own ID and leave ~60 bytes of residue,
//! and match nothing under the disc's — `nod` seeds every partition
//! from the disc header, which only coincides on the data partition).
//! So a partition's plaintext walks with [`crate::gcm::parse_volume`]
//! verbatim; a partition whose seed is the disc's shares the disc's one
//! junk stream (the same generator over a prefix of the same address
//! space), any other claims its own.
//!
//! # Verification before any claim
//!
//! The body's rebuild is `encrypt(plaintext, common key)`. It is claimed
//! only after this module has decrypted every sector, recomputed the
//! H0/H1/H2 tree from the plaintext and compared it to the disc's own
//! hash blocks BYTE FOR BYTE — padding included, because that is what
//! re-encryption reproduces. A partition that fails stays an opaque
//! piece of the disc (the decomposition of the disc around it is still
//! exact); a wrong guess costs storage, never a wrong claim, and D4
//! replay is the proof either way. Structural anomalies are settled
//! conclusions ([`Refusal`]), never environmental errors (D81).

