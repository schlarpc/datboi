/// The disc header's facts the walk needs.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DiscHeader {
    pub game_id: [u8; 6],
    pub disc: u8,
}

/// A ticket's key-selecting fields (the rest rides as a piece).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Ticket {
    pub issuer: String,
    pub wrapped_title_key: [u8; 16],
    pub title_id: [u8; 8],
    pub common_key_index: u8,
}

/// One partition as the table and its header describe it, offsets
/// absolute in the image.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PartitionHeader {
    /// Position in table order.
    pub index: usize,
    pub kind: u32,
    pub offset: u64,
    pub ticket: Ticket,
    pub tmd_offset: u64,
    pub tmd_len: u64,
    pub cert_offset: u64,
    pub cert_len: u64,
    pub h3_offset: u64,
    pub data_offset: u64,
    pub data_len: u64,
}

impl PartitionHeader {
    /// Sectors in the body.
    #[must_use]
    pub fn sectors(&self) -> u64 {
        self.data_len / SECTOR
    }

    /// Plaintext length of the body.
    #[must_use]
    pub fn plain_len(&self) -> u64 {
        self.sectors() * DATA_LEN as u64
    }

    /// Piece name prefix: `part<index>-<kind>` — the kind by name, or a
    /// channel partition's four-character code (a real disc's channel
    /// partitions carry their title ID as the kind).
    #[must_use]
    pub fn prefix(&self) -> String {
        let kind = match self.kind {
            KIND_DATA => "data".to_owned(),
            KIND_UPDATE => "update".to_owned(),
            KIND_CHANNEL => "channel".to_owned(),
            k => {
                let b = k.to_be_bytes();
                if b.iter().all(|c| c.is_ascii_alphanumeric()) {
                    String::from_utf8_lossy(&b).into_owned()
                } else {
                    format!("kind{k}")
                }
            }
        };
        format!("part{}-{kind}", self.index)
    }
}

fn be32(buf: &[u8], at: usize) -> u64 {
    u64::from(u32::from_be_bytes([
        buf[at],
        buf[at + 1],
        buf[at + 2],
        buf[at + 3],
    ]))
}

/// True if `head` (≥ 0x20 bytes at offset 0) carries the Wii magic.
#[must_use]
pub fn looks_like_wii(head: &[u8]) -> bool {
    head.len() >= 0x1C && head[0x18..0x1C] == WII_MAGIC
}

/// Read and check the disc header.
///
/// # Errors
/// [`WiiError::Refused`] for anything but an encrypted, hashed Wii
/// master; `Io` is environmental.
pub fn read_disc_header<R: Read + Seek>(img: &mut R) -> Result<DiscHeader, WiiError> {
    let total_len = img.seek(SeekFrom::End(0))?;
    if total_len < REGION_OFFSET + REGION_LEN {
        return Err(Refusal::NotWii.into());
    }
    let head = read_at(img, 0, usize::try_from(HEADER_LEN).expect("small"))?;
    if gcm::looks_like_gcm(&head) {
        return Err(Refusal::GameCube.into());
    }
    if !looks_like_wii(&head) {
        return Err(Refusal::NotWii.into());
    }
    if head[0x60] != 0 {
        return Err(Refusal::NoHashes.into());
    }
    if head[0x61] != 0 {
        return Err(Refusal::NoEncryption.into());
    }
    Ok(DiscHeader {
        game_id: head[..6].try_into().expect("6 bytes"),
        disc: head[6],
    })
}

/// Read the partition table and every partition's header. Cheap — a
/// few small reads — so the analyzer can resolve keys before any
/// heavy work.
///
/// # Errors
/// Structural lies are refusals; `Io` is environmental.
pub fn read_partitions<R: Read + Seek>(img: &mut R) -> Result<Vec<PartitionHeader>, WiiError> {
    let total_len = img.seek(SeekFrom::End(0))?;
    let groups = read_at(
        img,
        PARTITION_TABLE,
        usize::try_from(PARTITION_GROUPS * 8).expect("small"),
    )?;
    let mut entries: Vec<(u64, u32)> = Vec::new();
    for g in 0..PARTITION_GROUPS {
        let at = usize::try_from(g * 8).expect("small");
        let count = be32(&groups, at);
        let entries_off = be32(&groups, at + 4) << 2;
        if count == 0 {
            continue;
        }
        if count > MAX_PARTITIONS || entries.len() as u64 + count > MAX_PARTITIONS {
            return Err(Refusal::Header(format!(
                "partition group {g} declares {count} partitions"
            ))
            .into());
        }
        if entries_off + count * 8 > total_len {
            return Err(Refusal::Truncated("partition entries past the image").into());
        }
        let block = read_at(
            img,
            entries_off,
            usize::try_from(count * 8).expect("bounded"),
        )?;
        for i in 0..usize::try_from(count).expect("bounded") {
            let offset = be32(&block, i * 8) << 2;
            let kind = u32::try_from(be32(&block, i * 8 + 4)).expect("u32");
            entries.push((offset, kind));
        }
    }
    if entries.is_empty() {
        return Err(Refusal::Header("no partitions".into()).into());
    }
    let mut parts = Vec::with_capacity(entries.len());
    for (index, (offset, kind)) in entries.into_iter().enumerate() {
        if !offset.is_multiple_of(SECTOR) {
            return Err(Refusal::Partition(index, "offset is not sector aligned".into()).into());
        }
        if offset + PARTITION_HEADER_LEN > total_len {
            return Err(Refusal::Truncated("partition header past the image").into());
        }
        let h = read_at(
            img,
            offset,
            usize::try_from(PARTITION_HEADER_LEN).expect("small"),
        )?;
        let issuer_bytes = &h[0x140..0x180];
        let issuer = issuer_bytes
            .split(|&b| b == 0)
            .next()
            .map(|s| String::from_utf8_lossy(s).into_owned())
            .unwrap_or_default();
        let ticket = Ticket {
            issuer,
            wrapped_title_key: h[0x1BF..0x1CF].try_into().expect("16 bytes"),
            title_id: h[0x1DC..0x1E4].try_into().expect("8 bytes"),
            common_key_index: h[0x1F1],
        };
        let tmd_len = be32(&h, 0x2A4);
        let tmd_offset = offset + (be32(&h, 0x2A8) << 2);
        let cert_len = be32(&h, 0x2AC);
        let cert_offset = offset + (be32(&h, 0x2B0) << 2);
        let h3_offset = offset + (be32(&h, 0x2B4) << 2);
        let data_offset = offset + (be32(&h, 0x2B8) << 2);
        let data_len = be32(&h, 0x2BC) << 2;
        if tmd_len > MAX_META_LEN || cert_len > MAX_META_LEN {
            return Err(Refusal::Partition(
                index,
                "implausible tmd or certificate chain size".into(),
            )
            .into());
        }
        if !data_offset.is_multiple_of(SECTOR) || !data_len.is_multiple_of(SECTOR) {
            return Err(Refusal::Partition(index, "body is not sector aligned".into()).into());
        }
        if data_len == 0 {
            return Err(Refusal::Partition(index, "empty body".into()).into());
        }
        for (what, end) in [
            ("tmd", tmd_offset + tmd_len),
            ("certificate chain", cert_offset + cert_len),
            ("h3 table", h3_offset + H3_LEN),
            ("body", data_offset + data_len),
        ] {
            if end > total_len {
                return Err(Refusal::Partition(index, format!("{what} past the image")).into());
            }
        }
        parts.push(PartitionHeader {
            index,
            kind,
            offset,
            ticket,
            tmd_offset,
            tmd_len,
            cert_offset,
            cert_len,
            h3_offset,
            data_offset,
            data_len,
        });
    }
    Ok(parts)
}

/// Which known key a ticket selects.
#[must_use]
pub fn key_for<'k>(keys: &'k [KnownKey], ticket: &Ticket) -> Option<&'k KnownKey> {
    keys.iter()
        .find(|k| k.issuer == ticket.issuer && k.index == ticket.common_key_index)
}

/// What the verification pass concluded about one body.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BodyVerdict {
    /// blake3 of the encrypted body — the piece's identity.
    pub body_hash: Blake3,
    /// blake3 of the plaintext — the decrypt route's output identity.
    pub plain_hash: Blake3,
    /// Every hash block equals what its group's plaintext yields.
    pub verified: bool,
    /// The first sector whose hash block disagreed, when not verified.
    pub first_bad_sector: Option<u64>,
}

/// One sequential pass over a body: decrypt every sector, recompute
/// each group's tree, compare the hash blocks, and hash both the
/// ciphertext and the plaintext on the way.
///
/// # Errors
/// I/O only — a disagreeing hash block is a verdict, not an error.
pub fn verify_body<R: Read + Seek>(
    img: &mut R,
    part: &PartitionHeader,
    key: &Key,
) -> io::Result<BodyVerdict> {
    let title = title_key(key, &part.ticket.wrapped_title_key, &part.ticket.title_id);
    let sectors = part.sectors();
    let mut body_hasher = blake3::Hasher::new();
    let mut plain_hasher = blake3::Hasher::new();
    let mut verified = true;
    let mut first_bad = None;
    let mut enc = vec![0u8; usize::try_from(GROUP_LEN).expect("2 MiB")];
    let mut plain = vec![0u8; DATA_LEN * GROUP_SECTORS];
    let mut sector_plain = [0u8; SECTOR_LEN];
    img.seek(SeekFrom::Start(part.data_offset))?;
    let mut done = 0u64;
    while done < sectors {
        let n = usize::try_from((sectors - done).min(GROUP_SECTORS as u64)).expect("<= 64");
        let take = n * SECTOR_LEN;
        img.read_exact(&mut enc[..take])?;
        body_hasher.update(&enc[..take]);
        for s in 0..n {
            let e: &[u8; SECTOR_LEN] = enc[s * SECTOR_LEN..(s + 1) * SECTOR_LEN]
                .try_into()
                .expect("exact");
            decrypt_sector(&title, e, &mut sector_plain);
            plain[s * DATA_LEN..(s + 1) * DATA_LEN]
                .copy_from_slice(&sector_plain[SECTOR_LEN - DATA_LEN..]);
            // Keep the decrypted hash block for the comparison below.
            enc[s * SECTOR_LEN..s * SECTOR_LEN + (SECTOR_LEN - DATA_LEN)]
                .copy_from_slice(&sector_plain[..SECTOR_LEN - DATA_LEN]);
        }
        plain_hasher.update(&plain[..n * DATA_LEN]);
        if verified {
            let hashes = GroupHashes::compute(&plain[..n * DATA_LEN]);
            for s in 0..n {
                sector_plain[..SECTOR_LEN - DATA_LEN].copy_from_slice(
                    &enc[s * SECTOR_LEN..s * SECTOR_LEN + (SECTOR_LEN - DATA_LEN)],
                );
                if !hash_block_matches(&sector_plain, &hashes, s) {
                    verified = false;
                    first_bad = Some(done + s as u64);
                    break;
                }
            }
        }
        done += n as u64;
    }
    Ok(BodyVerdict {
        body_hash: Blake3(*body_hasher.finalize().as_bytes()),
        plain_hash: Blake3(*plain_hasher.finalize().as_bytes()),
        verified,
        first_bad_sector: first_bad,
    })
}

/// `Read + Seek` over a partition's plaintext, decrypting sectors on
/// demand out of the image with a one-sector cache — the `rom` the
/// volume walker and the piece hasher read through.
pub struct PlainReader<'r, R> {
    img: &'r mut R,
    base: u64,
    sectors: u64,
    key: Key,
    pos: u64,
    cached: u64,
    enc: Box<[u8; SECTOR_LEN]>,
    data: Box<[u8; DATA_LEN]>,
}

impl<'r, R: Read + Seek> PlainReader<'r, R> {
    /// Over `part`'s body under the common key `key`.
    pub fn new(img: &'r mut R, part: &PartitionHeader, key: &Key) -> Self {
        Self {
            img,
            base: part.data_offset,
            sectors: part.sectors(),
            key: title_key(key, &part.ticket.wrapped_title_key, &part.ticket.title_id),
            pos: 0,
            cached: u64::MAX,
            enc: Box::new([0u8; SECTOR_LEN]),
            data: Box::new([0u8; DATA_LEN]),
        }
    }

    /// Plaintext length.
    #[must_use]
    pub fn len(&self) -> u64 {
        self.sectors * DATA_LEN as u64
    }

    /// True when the body has no sectors.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.sectors == 0
    }

    fn load(&mut self, sector: u64) -> io::Result<()> {
        if self.cached == sector {
            return Ok(());
        }
        self.img
            .seek(SeekFrom::Start(self.base + sector * SECTOR))?;
        self.img.read_exact(&mut self.enc[..])?;
        decrypt_data(&self.key, &self.enc, &mut self.data[..]);
        self.cached = sector;
        Ok(())
    }
}

impl<R: Read + Seek> Read for PlainReader<'_, R> {
    fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
        let len = self.len();
        if self.pos >= len || buf.is_empty() {
            return Ok(0);
        }
        let sector = self.pos / DATA_LEN as u64;
        let within = usize::try_from(self.pos % DATA_LEN as u64).expect("< sector");
        self.load(sector)?;
        let n = (DATA_LEN - within)
            .min(buf.len())
            .min(usize::try_from(len - self.pos).unwrap_or(usize::MAX));
        buf[..n].copy_from_slice(&self.data[within..within + n]);
        self.pos += n as u64;
        Ok(n)
    }
}

impl<R: Read + Seek> Seek for PlainReader<'_, R> {
    fn seek(&mut self, pos: SeekFrom) -> io::Result<u64> {
        let len = self.len();
        let next = match pos {
            SeekFrom::Start(p) => Some(p),
            SeekFrom::End(d) => len.checked_add_signed(d),
            SeekFrom::Current(d) => self.pos.checked_add_signed(d),
        };
        let next = next.ok_or_else(|| io::Error::other("seek before start"))?;
        self.pos = next;
        Ok(next)
    }
}

/// One partition's part of the layout.
#[derive(Debug)]
pub struct PartitionLayout {
    pub header: PartitionHeader,
    pub verdict: BodyVerdict,
    /// The plaintext's coverage map — `None` when the body did not
    /// verify (it stays an opaque piece of the disc) or its plaintext
    /// is not a volume the walker accepts.
    pub plain: Option<gcm::Layout>,
    /// Why `plain` is `None`, for the verdict detail.
    pub opaque_reason: Option<String>,
    /// Index of the body piece in [`Layout::pieces`].
    pub body_piece: usize,
    /// The partition's junk seed: its boot block's ID and disc number.
    pub seed: ([u8; 4], u8),
    /// The partition's OWN junk stream — `Some` only when its seed is
    /// not the disc's and junk matched; otherwise its junk ranges are
    /// ranges of [`Layout::junk`].
    pub junk: Option<Junk>,
}

#[derive(Debug)]
pub struct Layout {
    pub total_len: u64,
    pub header: DiscHeader,
    /// The disc's own coverage map: header structures, per-partition
    /// tickets / TMDs / certificate chains / H3 tables as pieces,
    /// bodies as pieces (pre-hashed by the verification pass), gaps
    /// classified. [`Region::Extern`] regions reference the junk stream
    /// (extern input 0) at disc offsets.
    pub pieces: Vec<Piece>,
    pub regions: Vec<Region>,
    /// Hashes already computed for pieces (the bodies), by piece index.
    pub prehashed: HashMap<usize, Blake3>,
    pub partitions: Vec<PartitionLayout>,
    /// The disc's junk stream over its whole address space: `Some` when
    /// junk matched on the disc itself or inside a partition seeded like
    /// the disc (the data partition).
    pub junk: Option<Junk>,
    /// Disc-level (outside the bodies) classification.
    pub junk_bytes: u64,
    pub fill_bytes: u64,
    pub residual_bytes: u64,
}

impl Layout {
    /// Junk bytes matched across the disc and every walked partition.
    #[must_use]
    pub fn total_junk_bytes(&self) -> u64 {
        self.junk_bytes
            + self
                .partitions
                .iter()
                .filter_map(|p| p.plain.as_ref())
                .map(|l| l.junk_bytes)
                .sum::<u64>()
    }
}

