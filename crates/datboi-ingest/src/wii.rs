/// Length of the disc header the walk keeps as a literal.
pub const HEADER_LEN: u64 = 0x400;
/// The partition table: four `(count, entries offset)` groups.
pub const PARTITION_TABLE: u64 = 0x40000;
const PARTITION_GROUPS: u64 = 4;
/// region.bin.
pub const REGION_OFFSET: u64 = 0x4E000;
pub const REGION_LEN: u64 = 0x20;
/// A partition header: the ticket, then seven `u32`s.
pub const PARTITION_HEADER_LEN: u64 = 0x2C0;
pub const TICKET_LEN: u64 = 0x2A4;
/// The H3 table's fixed size.
pub const H3_LEN: u64 = 0x18000;
/// Partition kinds as the table names them.
pub const KIND_DATA: u32 = 0;
pub const KIND_UPDATE: u32 = 1;
pub const KIND_CHANNEL: u32 = 2;
/// A table claiming more partitions than this is a lie.
const MAX_PARTITIONS: u64 = 64;
/// A TMD or certificate chain above this is a lie.
const MAX_META_LEN: u64 = 1 << 20;
const SECTOR: u64 = SECTOR_LEN as u64;
const GROUP_LEN: u64 = SECTOR * GROUP_SECTORS as u64;

/// Structural refusals — deterministic conclusions about the bytes.
#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum Refusal {
    #[error("not a wii disc (no magic at 0x18)")]
    NotWii,
    #[error("a gamecube disc (magic at 0x1c) — not a wii image")]
    GameCube,
    #[error("truncated: {0}")]
    Truncated(&'static str),
    #[error("header: {0}")]
    Header(String),
    #[error("partition {0}: {1}")]
    Partition(usize, String),
    #[error("declared ranges overlap: {0} and {1}")]
    Overlap(String, String),
    #[error(
        "partition {0}: ticket issuer {1:?} / common key index {2} is not a key this build knows"
    )]
    UnknownKey(usize, String, u8),
    #[error(
        "the header declares no partition hashes — a decrypted or scrubbed image, not a master"
    )]
    NoHashes,
    #[error("the header declares no partition encryption — a decrypted image, not a master")]
    NoEncryption,
}

#[derive(Debug, thiserror::Error)]
pub enum WiiError {
    #[error(transparent)]
    Io(#[from] io::Error),
    #[error(transparent)]
    Refused(#[from] Refusal),
}

impl From<GcmError> for WiiError {
    fn from(e: GcmError) -> Self {
        match e {
            GcmError::Io(e) => Self::Io(e),
            GcmError::Refused(r) => Self::Refused(Refusal::Header(r.to_string())),
        }
    }
}

